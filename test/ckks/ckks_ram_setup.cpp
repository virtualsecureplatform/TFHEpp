#include "ckks_ram_output_switch.hpp"
using namespace TFHEpp;
int main(int argc,char **argv)try {
    if(argc==4 && std::string(argv[1])=="--add-ring-switch-keys")return ckks_ram::addRingSwitchKeys(argv[2],argv[3]);
    const bool retune=argc==5&&std::string(argv[1])=="--retune-lvl1-sigma256";
    if(argc!=3&&!retune)throw std::runtime_error("usage: ckks_ram_setup CHECKPOINT NEW_FIXTURE_DIRECTORY | --retune-lvl1-sigma256 CHECKPOINT LEGACY_FIXTURE NEW_FIXTURE");
#ifndef USE_LVL1_SIGMA256
    if(retune)throw std::runtime_error("retuning requires USE_LVL1_SIGMA256=ON");
#endif
    const std::filesystem::path root=retune?argv[4]:argv[2];
    const std::filesystem::path checkpoint=retune?argv[2]:argv[1];
    if(std::string(argv[1])=="--add-traces"){
        auto sk=std::make_unique<ckks_ram::SavedOwner>();ckks_ram::load(root/"owner.bin",*sk);
        ckks_ram::saveTrace<2,2>(root,sk->secret(),"trace-4x2.bin");
        ckks_ram::saveTrace<8,1>(root,sk->secret(),"trace-256x1.bin");
        ckks_ram::saveTrace<9,1>(root,sk->secret(),"trace-512x1.bin");
        ckks_ram::saveTrace<10,1>(root,sk->secret(),"trace-1024x1.bin");
        ckks_ram::saveTrace<13,1>(root,sk->secret(),"trace-8192x1.bin");
        std::cout<<"Saved missing traces; existing keys and traces reused"<<std::endl;return 0;
    }
    if(!std::filesystem::create_directory(root))throw std::runtime_error("setup requires a new directory; reuse existing fixture instead");
    auto dense=std::make_unique<Key<ckks_ram::P>>(),sparse=std::make_unique<Key<ckks_ram::P>>();
    {std::ifstream f(checkpoint/"checkpoint.bin",std::ios::binary);if(!f)throw std::runtime_error("missing checkpoint");
     cereal::PortableBinaryInputArchive ar(f);std::array<uint64_t,9> meta;std::string name;ar(meta,name);
     if(meta!=std::array<uint64_t,9>{0x4e415252504b3031ULL,16384,85,41,379,49,34,100,448}||name!="tanh")throw std::runtime_error("checkpoint mismatch");
     ar(*dense,*sparse);}
    std::unique_ptr<SecretKey> sk;
    if(retune){
        auto old=std::make_unique<ckks_ram::SavedOwner>();
        std::ifstream f(std::filesystem::path(argv[3])/"owner.bin",std::ios::binary);
        if(!f)throw std::runtime_error("missing legacy private owner");
        cereal::PortableBinaryInputArchive ar(f);
        // A mutable fixed header is needed by input archives.
        std::array<std::uint64_t,7> stored{};ar(stored);
        if(stored!=ckks_ram::legacy_metadata)throw std::runtime_error("legacy owner profile mismatch");
        ar(old->keys);old->params.readLegacyPrivateOwner(ar);
        if(f.peek()!=std::char_traits<char>::eof())throw std::runtime_error("legacy owner trailing data");
        sk=std::make_unique<SecretKey>(SecretKey{lweKey{std::move(old->keys)},lweParams{}});
    }else sk=std::make_unique<SecretKey>();
    ckks_ram::save(root/"owner.bin",*sk);
    std::filesystem::permissions(root/"owner.bin",std::filesystem::perms::owner_read|std::filesystem::perms::owner_write);
    auto ek=std::make_unique<EvalKey>();
    ek->emplaceiksk<ckks_ram::KS>(*sk);ek->emplacebkfft<ckks_ram::CB>(*sk);
    ek->emplacebkfft<ckks_ram::BR>(*sk);ek->emplaceprivksk4cb<ckks_ram::PKS>(*sk);
    ckks_ram::save(root/"tfhe-eval.bin",*ek);ek.reset();
    std::cout<<"TFHE setup saved"<<std::endl;
    const auto &secret=sk->key.getIndependent<ckks_ram::L>();
    ckks_ram::saveTrace<2,2>(root,secret,"trace-4x2.bin");
    ckks_ram::saveTrace<8,1>(root,secret,"trace-256x1.bin");
    if(retune){ckks_ram::saveTrace<9,1>(root,secret,"trace-512x1.bin");ckks_ram::saveTrace<10,1>(root,secret,"trace-1024x1.bin");ckks_ram::saveTrace<13,1>(root,secret,"trace-8192x1.bin");}
    auto pack=std::make_unique<ckks_ram::PackKey>();
    TLWECoefficientPackingKeyGen48(*pack,secret,*sparse);
    ckks_ram::save(root/"pack48.bin",*pack);pack.reset();
    std::cout<<"packing key saved"<<std::endl;
    auto output=std::make_unique<ckks_ram::OutKey>();
    CKKSToTFHEKeyGen<ckks_ram::P,ckks_ram::L,2,16>(*output,*dense,secret);
    ckks_ram::save(root/"to-tfhe32.bin",*output);
    output.reset();
    if(retune){
        ckks_ram::addRingSwitchKeys(checkpoint,root);
        std::ofstream report(root/"sigma256-setup.json");
        report<<"{\"lvl1_sigma\":256,\"circular_security_assumed\":true,\"security_validated\":false,\"diagnostic_owner_reused\":true,\"private_keys_generated\":0,\"all_tfhe_evaluation_material_regenerated\":true,\"input_ciphertexts_regenerated\":true,\"source_fixture_untouched\":true}\n";
        if(!report)throw std::runtime_error("retune setup receipt write failed");
    }
    std::cout<<"RAM setup complete; no keys are generated by the evaluator"<<std::endl;
}catch(const std::exception &e){std::cerr<<e.what()<<'\n';return 1;}
